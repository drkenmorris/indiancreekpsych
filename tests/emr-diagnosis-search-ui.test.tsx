import React from 'react';
import {afterEach,expect,test,vi} from 'vitest';
import {cleanup,fireEvent,render,screen,waitFor} from '@testing-library/react';
import DiagnosticReferenceSearch from '@/app/emr/diagnosis/DiagnosticReferenceSearch';
import {searchDiagnosticReferences} from '@/lib/emr/diagnosis-search';
afterEach(()=>{cleanup();vi.unstubAllGlobals();});
test('search stays within the EMR and Enter cannot submit the surrounding patient form',async()=>{
 const save=vi.fn(event=>event.preventDefault());
 const fetch=vi.fn(async(_url:string,options:RequestInit)=>{const body=JSON.parse(options.body as string);return {ok:true,json:async()=>searchDiagnosticReferences(body.query,body.source,body.offset)};});
 vi.stubGlobal('fetch',fetch);
 render(<form onSubmit={save}><DiagnosticReferenceSearch diagnosis="Generalized anxiety disorder"/><textarea defaultValue="Private clinical notes"/><button type="submit">Save diagnoses</button></form>);
 expect(fetch).not.toHaveBeenCalled();
 const input=screen.getByLabelText('Reference terms');
 fireEvent.change(input,{target:{value:'GAD'}});
 fireEvent.keyDown(input,{key:'Enter'});
 await screen.findByRole('link',{name:/How is generalized anxiety disorder diagnosed/});
 expect(save).not.toHaveBeenCalled();
 expect(fetch.mock.calls[0][0]).toBe('/api/emr/diagnoses/search');
 expect(JSON.parse(fetch.mock.calls[0][1].body as string)).toEqual({query:'GAD',source:'all',offset:0});
 expect(fetch.mock.calls[0][1].body).not.toContain('Private clinical notes');
 const link=screen.getByRole('link',{name:/How is generalized anxiety disorder diagnosed/});
 expect(link.getAttribute('href')).toContain('#part_6119');
 expect(link.getAttribute('target')).toBe('_blank');
 fireEvent.change(screen.getByLabelText('Reference source'),{target:{value:'apa'}});
 fireEvent.click(screen.getByRole('button',{name:'bipolar'}));
 await screen.findByRole('link',{name:/Other specified bipolar disorder criteria changes/});
 expect(screen.getByText(/Topic link only/)).not.toBeNull();
});
test('late searches cannot replace newer search results and failures support retry',async()=>{
 let finish:(result:unknown)=>void=()=>{};
 const fetch=vi.fn().mockImplementationOnce(()=>new Promise(resolve=>{finish=resolve;})).mockResolvedValueOnce({ok:true,json:async()=>searchDiagnosticReferences('outpatient','all')}).mockRejectedValueOnce(Error('Search unavailable')).mockResolvedValue({ok:true,json:async()=>searchDiagnosticReferences('GAD','all')});
 vi.stubGlobal('fetch',fetch);
 render(<DiagnosticReferenceSearch diagnosis="Generalized anxiety disorder"/>);
 fireEvent.click(screen.getByRole('button',{name:'GAD'}));
 fireEvent.click(screen.getByRole('button',{name:'outpatient'}));
 await screen.findByText('outpatient',{selector:'strong'});
 finish({ok:true,json:async()=>searchDiagnosticReferences('GAD')});
 await waitFor(()=>expect(screen.queryByText('GAD',{selector:'strong'})).toBeNull());
 fireEvent.click(screen.getByRole('button',{name:'Search references'}));
 await screen.findByText('Search unavailable');
 fireEvent.click(screen.getByRole('button',{name:'GAD'}));
 await screen.findByText('GAD',{selector:'strong'});
});
